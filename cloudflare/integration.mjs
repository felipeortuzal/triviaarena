import assert from "node:assert/strict";
const base=process.env.RIVIERA_URL||"http://127.0.0.1:8787";
async function call(path,method="GET",data,token){
 const resp=await fetch(base+path,{method,headers:{"content-type":"application/json",...(token?{authorization:"Bearer "+token}:{})},body:data?JSON.stringify(data):undefined});
 return {status:resp.status,data:await resp.json()};
}
const code=(await call("/api/status")).data;assert.equal(code.online,true);
const {status:createdStatus,data:host}=await call("/api/room","POST",{nick:"Player 1",mode:"rounds",target:1});
assert.equal(createdStatus,200);
assert.match(host.code,/^[A-HJ-NP-Z2-9]{6}$/);
const {status:joinStatus,data:guest}=await call("/api/room/"+host.code+"/join","POST",{nick:"Player 2"});
assert.equal(joinStatus,200);
assert.notEqual(host.token,guest.token);
const p="/api/room/"+host.code;
const {data:info}=await call("/api/status");
assert.equal(info.version,"2.1");
assert.equal(info.rankings,41);
const list=await call("/api/rankings");
assert.equal(list.data.rankings.length,41);
assert.equal(list.data.rankings.some(b=>b.id==="f1-2025"),true);
assert.equal(list.data.rankings.some(b=>b.id==="epl-2025-26"),true);
assert.equal(list.data.rankings.some(b=>b.group==="Geografia"),true);
assert.equal((await call(p+"/ready","POST",{},guest.token)).status,200);
const ready=(await call(p,"GET",null,host.token)).data;
assert.equal(ready.players.find(q=>q.id===guest.id).ready,true);
assert.equal(ready.players.length,2);
assert.equal((await call(p+"/heartbeat","POST",{},guest.token)).status,200);
assert.equal((await call(p+"/handoff","POST",{playerId:guest.id},host.token)).status,200);
assert.equal((await call(p,"GET",null,guest.token)).data.isHost,true);
assert.equal((await call(p+"/handoff","POST",{playerId:host.id},guest.token)).status,200);
const spectator=(await call(p+"/join","POST",{nick:"Terceiro"})).data;
assert.equal((await call(p+"/kick","POST",{playerId:spectator.id},guest.token)).status,403);
assert.equal((await call(p+"/kick","POST",{playerId:spectator.id},host.token)).status,200);
assert.equal((await call(p,"GET",null,spectator.token)).status,403);
assert.equal((await call(p+"/react","POST",{emoji:"%INVALID%"},guest.token)).status,400);
assert.equal((await call(p+"/react","POST",{emoji:"🔥"},guest.token)).status,200);
const reactionState=(await call(p,"GET",null,host.token)).data;
assert.equal(reactionState.reactions.length,1);
assert.equal(reactionState.reactions[0].emoji,"🔥");
assert.equal(reactionState.reactions[0].nick,"Player 2");
assert.equal(Object.hasOwn(reactionState.reactions[0],"token"),false,"No visitor token in reactions");
assert.equal((await call(p+"/react","POST",{emoji:"😂"},guest.token)).status,429,"Rate limit stops emoji spam");
assert.equal((await call(p+"/react","POST",{emoji:"👏"},host.token)).status,200);
assert.equal((await call(p,"GET",null,guest.token)).data.reactions.length,2);

assert.equal((await call(p,"GET",null,"wrong-token")).status,403);
assert.equal((await call(p+"/start","POST",{},guest.token)).status,403);
assert.equal((await call(p+"/start","POST",{},host.token)).status,409,"Host cannot start without ready confirmations");
assert.equal((await call(p+"/ready","POST",{},host.token)).status,200);
assert.equal((await call(p+"/start","POST",{},host.token)).status,200);
const {data:start}=await call(p,"GET",null,host.token);
assert.equal(start.phase,"playing");
assert.equal(start.players.length,2);
assert.ok(start.deadline-start.serverNow>24000&&start.deadline-start.serverNow<=30000);
assert.ok(start.question.options.length===start.question.limit);
const options=start.question.options.map(x=>x.name);
const [answerA,answerB]=await Promise.all([
 call(p+"/guess","POST",{answer:options[0]},host.token),
 call(p+"/guess","POST",{answer:options[0]},guest.token)
]);
assert.equal([answerA.status,answerB.status].filter(x=>x===200).length,1,"Guess duplicate must have one winner");
assert.equal([answerA.status,answerB.status].filter(x=>x===409).length,1,"Duplicate must be rejected");
const {data:before}=await call(p,"GET",null,host.token);
