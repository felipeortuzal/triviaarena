import assert from "node:assert/strict";
import {existsSync} from "node:fs";
import {chromium} from "playwright-core";
const chrome=["/usr/bin/google-chrome","/usr/bin/chromium","/opt/google/chrome/chrome"].find(existsSync);
assert.ok(chrome,"Chrome/Chromium não encontrado");
const browser=await chromium.launch({headless:true,executablePath:chrome,args:["--no-sandbox"]});
const base="http://127.0.0.1:8787/";
try{
 const a=await browser.newContext({viewport:{width:1280,height:900}});
 const b=await browser.newContext({viewport:{width:375,height:800}});
 const pa=await a.newPage(),pb=await b.newPage();
 const failures=[];
 for(const p of [pa,pb])p.on("pageerror",err=>failures.push(err.message));
 await pa.goto(base,{waitUntil:"networkidle"});
 await pa.locator(".hero-logo").waitFor({state:"visible"});
 assert.ok(await pa.locator(".hero-logo").evaluate(img=>img.complete&&img.naturalWidth>200),"Logo aprovada deve carregar");
 await pa.locator('[data-op="create"]').click();
 await pa.locator('#create-form [name="nick"]').fill("Afonso");
 await pa.locator('#create-form [name="target"]').fill("1");
 await pa.locator('#create-form button[type="submit"]').click();
 await pa.locator('.roomcode').waitFor({state:"visible"});
 const code=(await pa.locator('.roomcode').innerText()).trim();
 assert.match(code,/^[A-HJ-NP-Z2-9]{6}$/);
 await pb.goto(base+"?room="+code,{waitUntil:"domcontentloaded"});
 await pb.locator('#join-form [name="nick"]').fill("Bianca");
 await pb.locator('#join-form button[type="submit"]').click();
 await pb.locator('.roomcode').waitFor({state:"visible"});
 await pb.locator('[data-op="ready"]').click();
 await pa.getByText(/1 \/ 2/).waitFor({timeout:10000});
 assert.ok(await pa.locator('.player .sent.yes').count()>=1,"Lobby mostra jogador pronto");
 assert.ok(await pa.locator('[data-op="kick"]').count()===1,"Host pode remover no lobby");
 assert.ok(await pa.locator('[data-op="handoff"]').count()===1,"Host pode transferir liderança");
 await pa.locator('[data-op="start"]:not([disabled])').waitFor({state:"visible",timeout:10000});
 await pa.locator('[data-op="start"]').click();
 await pa.locator('#guess').waitFor({state:"visible"});
 await pb.locator('#guess').waitFor({state:"visible",timeout:10000});
 const options=await pa.evaluate(async()=>{
  const s=JSON.parse(localStorage.getItem("riviera-cloudflare-session-v1"));
  const r=await fetch("/api/room/"+s.code,{headers:{authorization:"Bearer "+s.token}});
  return (await r.json()).question.options.map(o=>o.name);
 });
 assert.ok(options.length>=25);
 await pa.locator('#guess').fill(options[0]);
 await pa.locator('#guess-form button[type="submit"]').click();
 await pa.getByText("PALPITE ENVIADO").waitFor({timeout:8000});
 await pb.locator('#guess').fill(options[1]);
 await pb.locator('#guess-form button[type="submit"]').click();
 await pa.getByText("FIM DE JOGO").waitFor({timeout:10000});
 await pb.getByText("FIM DE JOGO").waitFor({timeout:10000});
 assert.equal(await pa.locator(".result-row").count(),2);
 assert.equal(await pb.locator(".result-row").count(),2);
 const overflow=await pb.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
 assert.ok(overflow<=2,"Site não pode ter scroll horizontal no mobile: "+overflow);
 await pb.setViewportSize({width:320,height:700});
 const narrow=await pb.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
 assert.ok(narrow<=2,"HUD não pode exceder a largura de 320px: "+narrow);
 await pa.locator('[data-op="restart"]').click();
 await pa.locator('#guess').waitFor({state:"visible",timeout:10000});
 await pb.locator('#guess').waitFor({state:"visible",timeout:10000});
 assert.deepEqual(failures,[],"Erros de JavaScript no navegador");
 console.log("NAVEGADOR MULTIPLAYER OK: dois Chromes, convite, lobby, envios simultâneos, revelação, mobile, revanche.");
 await a.close();await b.close();
}finally{await browser.close()}
